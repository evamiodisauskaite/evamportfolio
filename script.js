const i18nNodes = [...document.querySelectorAll("[data-i18n]")];
const lt = new Map(i18nNodes.map((node) => [node, node.textContent]));

function readLang() {
  try { return localStorage.getItem("portfolio-lang") || "lt"; } catch (error) { return "lt"; }
}

let currentLang = "lt";

function applyLanguage(lang) {
  currentLang = lang;
  i18nNodes.forEach((node) => {
    const value = lang === "en" ? en[node.dataset.i18n] : lt.get(node);
    if (value) node.textContent = value;
  });
  document.documentElement.lang = lang;
  const toggle = document.querySelector(".lang-toggle");
  if (toggle) toggle.textContent = lang === "lt" ? "EN" : "LT";
  try { localStorage.setItem("portfolio-lang", lang); } catch (error) { /* private mode */ }
}

document.querySelector(".lang-toggle")?.addEventListener("click", () => applyLanguage(currentLang === "lt" ? "en" : "lt"));
if (readLang() === "en") applyLanguage("en");

document.getElementById("year").textContent = new Date().getFullYear();

/* ---------- footer name: always exactly as wide as the page ---------- */
const wordmark = document.querySelector(".wordmark");

function fitWordmark() {
  if (!wordmark) return;
  const style = getComputedStyle(wordmark);
  const available = wordmark.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight);
  const range = document.createRange();
  range.selectNodeContents(wordmark);
  const textWidth = range.getBoundingClientRect().width;
  if (!textWidth || !available) return;
  const size = parseFloat(style.fontSize) * (available / textWidth);
  wordmark.style.fontSize = `${Math.floor(size * 0.995)}px`;
}

fitWordmark();
document.fonts?.ready.then(fitWordmark);
window.addEventListener("resize", fitWordmark);

