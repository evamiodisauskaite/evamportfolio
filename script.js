/* ---------- Instagram strip arrows ---------- */
const igTrack = document.querySelector(".ig-track");
const igArrows = document.querySelectorAll(".ig-arrow");

function updateIgArrows() {
  if (!igTrack) return;
  const max = igTrack.scrollWidth - igTrack.clientWidth - 2;
  igArrows.forEach((arrow) => {
    arrow.disabled = arrow.dataset.dir === "-1" ? igTrack.scrollLeft <= 2 : igTrack.scrollLeft >= max;
  });
}

igArrows.forEach((arrow) => {
  arrow.addEventListener("click", () => {
    igTrack.scrollBy({ left: Number(arrow.dataset.dir) * igTrack.clientWidth * 0.8, behavior: "smooth" });
  });
});
igTrack?.addEventListener("scroll", updateIgArrows, { passive: true });
window.addEventListener("resize", updateIgArrows);
updateIgArrows();

